    /**
     * Generate a cohort characterization on a single data source
     *
     * @param id
     *         The id of an existing cohort characterization in WebAPI
     * @param sourceKey
     *         The identifier for the data source to generate against
     * @return A json object with information about the generation job included the status and execution id.
     */
    @PostMapping("/{id}/generation/{sourceKey}")
    @PreAuthorize("@authorizationManager.currentUserHasPermission(@PERMS.UPDATE_COHORT_CHARACTERIZATION) and @authorizationManager.currentUserHasPermission(@PERMS.READ_SOURCE)")
    public JobExecutionResource generate(
            @PathVariable("id") final Long id,
            @PathVariable("sourceKey") final String sourceKey) {
        checkUpdatePermission(id);

        if (!authorizationManager.currentUserCanRead(sourceKey)) {
            throw new AccessDeniedException("You do not have permission to read this data source");
        }

        var cc = service.findByIdWithLinkedEntities(id);
        ExceptionUtils.throwNotFoundExceptionIfNull(cc,
                String.format("There is no cohort characterization with id = %d.", id));
        var checkResult = runDiagnostics(convertCcToDto(cc));
        if (checkResult.hasCriticalErrors()) {
            throw new RuntimeException(
                    "Cannot be generated due to critical errors in design. Call 'check' service for further details");
        }
        return service.generateCc(id, sourceKey);
    }

