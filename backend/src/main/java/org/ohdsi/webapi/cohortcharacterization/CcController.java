    /**
     * Get list of cohort characterizations with assigned tags
     *
     * @param requestDTO
     * @return
     */
    @PostMapping("/byTags")
    @PreAuthorize("@authorizationManager.currentUserHasPermission(@PERMS.READ_COHORT_CHARACTERIZATION)")
    public List<CcShortDTO> listByTags(@RequestBody TagNameListRequestDTO requestDTO) {
        if (requestDTO == null || requestDTO.names() == null || requestDTO.names().isEmpty()) {
            return Collections.emptyList();
        }
        var taggedEntities = service.listByTags(requestDTO);
        return taggedEntities
                .stream()
                .filter(!webApiProperties.security().defaultGlobalReadPermissions()
                        ? authorizationManager::currentUserCanRead
                        : entity -> true)
                .map(entity -> conversionService.convert(entity, CcShortDTO.class))
                .collect(Collectors.toList());
    }

    private void convertPresetAnalysesToLocal(List<? extends CcResult> ccResults) {
        var presetFeAnalyses = feAnalysisService.findPresetAnalysesBySystemNames(
                ccResults
                        .stream()
                        .map(CcResult::getAnalysisName)
                        .distinct()
                        .collect(Collectors.toList()));
        ccResults.stream().filter(res -> Objects.equals(res.getFaType(), StandardFeatureAnalysisType.PRESET.name()))
                .forEach(res -> {
                    presetFeAnalyses.stream().filter(fa -> fa.getDesign().equals(res.getAnalysisName())).findFirst()
                            .ifPresent(fa -> {
                                res.setAnalysisId(fa.getId());
                                res.setAnalysisName(fa.getName());
                            });
                });
    }

    private Integer convertPresetAnalysisIdToSystem(Integer analysisId) {
        var fe = feAnalysisService.findById(analysisId).orElse(null);
        if (fe instanceof FeAnalysisWithStringEntity && fe.isPreset()) {
            FeatureExtraction.PrespecAnalysis prespecAnalysis = FeatureExtraction.getNameToPrespecAnalysis()
                    .get(((FeAnalysisWithStringEntity) fe).getDesign());
            return prespecAnalysis.analysisId;
        }
        return analysisId;
    }

    private void checkReadPermission(long id) {
        if (this.webApiProperties.security().defaultGlobalReadPermissions()) {
            return;
        }
        if (!authorizationManager.currentUserCanRead(SecuredEntityType.COHORT_CHARACTERIZATION, id)) {
            throw new AccessDeniedException(
                    String.format("User doesn't have permission to read Cohort Characterization with id = %d", id));
        }
    }

    private void checkUpdatePermission(long id) {
        if (!authorizationManager.currentUserCanUpdate(SecuredEntityType.COHORT_CHARACTERIZATION, id)) {
            throw new AccessDeniedException(
                    String.format("User doesn't have permission to update Cohort Characterization with id = %d", id));
        }
    }
