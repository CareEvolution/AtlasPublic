package org.ohdsi.webapi.cohortsample;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;
import java.util.Map;

import org.ohdsi.webapi.authorization.AuthorizationManager;
import org.ohdsi.webapi.cohortdefinition.CohortDefinitionRepository;
import org.ohdsi.webapi.cohortdefinition.CohortGenerationInfoId;
import org.ohdsi.webapi.cohortdefinition.CohortGenerationInfoRepository;
import org.ohdsi.webapi.cohortsample.dto.CohortSampleDTO;
import org.ohdsi.webapi.cohortsample.dto.CohortSampleListDTO;
import org.ohdsi.webapi.cohortsample.dto.SampleParametersDTO;
import org.ohdsi.webapi.generationtasks.GenerationStatus;
import org.ohdsi.webapi.source.SourceEntity;
import org.ohdsi.webapi.source.SourceRepository;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import jakarta.ws.rs.BadRequestException;
import jakarta.ws.rs.NotFoundException;
import jakarta.ws.rs.core.Response;

/**
 * REST API for Cohort Sampling. Cohort sampling is a process of generating a sample of persons 
 * from a cohort of interest. The sample is generated by executing a set of sampling parameters 
 * against the cohort and a data source. The results are stored in WebAPI and can be retrieved by the client.
 */
@RestController
@RequestMapping("/cohortsample")
public class CohortSamplingController {
    private final CohortDefinitionRepository cohortDefinitionRepository;
    private final CohortGenerationInfoRepository generationInfoRepository;
    private final CohortSamplingService samplingService;
    private final SourceRepository sourceRepository;
    private final AuthorizationManager authorizationManager;

    public CohortSamplingController(
            CohortSamplingService samplingService,
            SourceRepository sourceRepository,
            CohortDefinitionRepository cohortDefinitionRepository,
            CohortGenerationInfoRepository generationInfoRepository,
            AuthorizationManager authorizationManager
    ) {
        this.samplingService = samplingService;
        this.sourceRepository = sourceRepository;
        this.cohortDefinitionRepository = cohortDefinitionRepository;
        this.generationInfoRepository = generationInfoRepository;
        this.authorizationManager = authorizationManager;
    }

    /**
     * Get information about cohort samples for a data source
     *
     * @param cohortDefinitionId
     *         The id for an existing cohort definition
     * @param sourceKey
     * @return JSON containing information about cohort samples
     */
    @GetMapping("/{cohortDefinitionId}/{sourceKey}")
    @PreAuthorize("@authorizationManager.currentUserHasPermission(@PERMS.READ_COHORT_DEFINITION) and @authorizationManager.currentUserHasPermission(@PERMS.READ_SOURCE)")
    public CohortSampleListDTO listCohortSamples(
            @PathVariable("cohortDefinitionId") int cohortDefinitionId,
            @PathVariable("sourceKey") String sourceKey
    ) {
        checkPermissions(cohortDefinitionId, sourceKey);
        SourceEntity source = getSource(sourceKey);
        CohortSampleListDTO result = new CohortSampleListDTO();

        result.setCohortDefinitionId(cohortDefinitionId);
        result.setSourceId(source.getId());

        var generationInfo = generationInfoRepository.findById(
                new CohortGenerationInfoId(cohortDefinitionId, source.getId()));

        result.setGenerationStatus(generationInfo.isPresent() ? generationInfo.get().getStatus() : null);
        result.setIsValid(generationInfo.isPresent() && generationInfo.get().isIsValid());

        result.setSamples(this.samplingService.listSamples(cohortDefinitionId, source.getId()));

        return result;
    }

    /**
     * Get an existing cohort sample
     *
     * @param cohortDefinitionId
     * @param sourceKey
     * @param sampleId
     * @param fields
     * @return personId, gender, age of each person in the cohort sample
     */
    @GetMapping("/{cohortDefinitionId}/{sourceKey}/{sampleId}")
    @PreAuthorize("@authorizationManager.currentUserHasPermission(@PERMS.READ_COHORT_DEFINITION) and @authorizationManager.currentUserHasPermission(@PERMS.READ_SOURCE)")
    public CohortSampleDTO getCohortSample(
            @PathVariable("cohortDefinitionId") int cohortDefinitionId,
            @PathVariable("sourceKey") String sourceKey,
            @PathVariable("sampleId") Integer sampleId,
            @RequestParam(defaultValue = "",  name = "fields") String fields
    ) {
        checkPermissions(cohortDefinitionId, sourceKey);
        List<String> returnFields = Arrays.asList(fields.split(","));
        boolean withRecordCounts = returnFields.contains("recordCount");
        return this.samplingService.getSample(sampleId, withRecordCounts);
    }

    /**
     * Refresh a cohort sample Refresh a cohort sample for a given source key. This will re-sample persons from the cohort.
     * 
     * @param cohortDefinitionId
     * @param sourceKey
     * @param sampleId
     * @param fields
     * @return A sample of persons from a cohort
     *
     */
    @PostMapping("/{cohortDefinitionId}/{sourceKey}/{sampleId}/refresh")
    @PreAuthorize("@authorizationManager.currentUserHasPermission(@PERMS.UPDATE_COHORT_DEFINITION) and @authorizationManager.currentUserHasPermission(@PERMS.READ_SOURCE)")
    public CohortSampleDTO refreshCohortSample(
            @PathVariable("cohortDefinitionId") int cohortDefinitionId,
            @PathVariable("sourceKey") String sourceKey,
            @PathVariable("sampleId") Integer sampleId,
            @RequestParam(name = "fields", defaultValue = "") String fields
    ) {
        checkUpdatePermissions(cohortDefinitionId, sourceKey);
        List<String> returnFields = Arrays.asList(fields.split(","));
        boolean withRecordCounts = returnFields.contains("recordCount");
        this.samplingService.refreshSample(sampleId);
        return this.samplingService.getSample(sampleId, withRecordCounts);
    }

    /**
     * Does an existing cohort have samples?
     *
     * @param cohortDefinitionId
     * @return true or false
     */
    @GetMapping("/has-samples/{cohortDefinitionId}")
    @PreAuthorize("@authorizationManager.currentUserHasPermission(@PERMS.READ_COHORT_DEFINITION)")
    public Map<String, Boolean> hasSamples(
            @PathVariable("cohortDefinitionId") int cohortDefinitionId
    ) {
        checkReadCohortDefinition(cohortDefinitionId);
        int nSamples = this.samplingService.countSamples(cohortDefinitionId);
        return Collections.singletonMap("hasSamples", nSamples > 0);
    }

    /**
     * Does an existing cohort have samples from a particular source?
     *
     * @param sourceKey
     * @param cohortDefinitionId
     * @return true or false
     */
    @GetMapping("/has-samples/{cohortDefinitionId}/{sourceKey}")
    @PreAuthorize("@authorizationManager.currentUserHasPermission(@PERMS.READ_COHORT_DEFINITION) and @authorizationManager.currentUserHasPermission(@PERMS.READ_SOURCE)")
    public Map<String, Boolean> hasSamples(
            @PathVariable("sourceKey") String sourceKey,
            @PathVariable("cohortDefinitionId") int cohortDefinitionId
    ) {
        checkPermissions(cohortDefinitionId, sourceKey);
        SourceEntity source = getSource(sourceKey);
        int nSamples = this.samplingService.countSamples(cohortDefinitionId, source.getId());
        return Collections.singletonMap("hasSamples", nSamples > 0);
    }

    /**
     * Create a new cohort sample
     *
     * @param sourceKey
     * @param cohortDefinitionId
     * @param sampleParameters
     * @return
     */
    @PostMapping("/{cohortDefinitionId}/{sourceKey}")
    @PreAuthorize("@authorizationManager.currentUserHasPermission(@PERMS.UPDATE_COHORT_DEFINITION) and @authorizationManager.currentUserHasPermission(@PERMS.READ_SOURCE)")
    public CohortSampleDTO createCohortSample(
            @PathVariable("sourceKey") String sourceKey,
            @PathVariable("cohortDefinitionId") int cohortDefinitionId,
            @RequestBody SampleParametersDTO sampleParameters
    ) {
        checkUpdatePermissions(cohortDefinitionId, sourceKey);
        sampleParameters.validate();
        SourceEntity source = getSource(sourceKey);
        var generationInfo = generationInfoRepository.findById(
                new CohortGenerationInfoId(cohortDefinitionId, source.getId()));
        if (!generationInfo.isPresent() || generationInfo.get().getStatus() != GenerationStatus.COMPLETE) {
            throw new BadRequestException("Cohort is not yet generated");
        }
        return samplingService.createSample(source, cohortDefinitionId, sampleParameters);
    }

    /**
     * Delete a cohort sample
     *
     * @param sourceKey
     * @param cohortDefinitionId
     * @param sampleId
     * @return
     */
    @DeleteMapping("/{cohortDefinitionId}/{sourceKey}/{sampleId}")
    @PreAuthorize("@authorizationManager.currentUserHasPermission(@PERMS.UPDATE_COHORT_DEFINITION) and @authorizationManager.currentUserHasPermission(@PERMS.READ_SOURCE)")
    public Response deleteCohortSample(
            @PathVariable("sourceKey") String sourceKey,
            @PathVariable("cohortDefinitionId") int cohortDefinitionId,
            @PathVariable("sampleId") int sampleId
    ) {
        checkUpdatePermissions(cohortDefinitionId, sourceKey);
        SourceEntity source = getSource(sourceKey);
        samplingService.deleteSample(cohortDefinitionId, source, sampleId);
        return Response.status(Response.Status.NO_CONTENT).build();
    }

    /**
     * Delete all samples for a cohort on a data source
     *
     * @param sourceKey
     * @param cohortDefinitionId
     * @return
     */
    @DeleteMapping("/{cohortDefinitionId}/{sourceKey}")
    @PreAuthorize("@authorizationManager.currentUserHasPermission(@PERMS.UPDATE_COHORT_DEFINITION) and @authorizationManager.currentUserHasPermission(@PERMS.READ_SOURCE)")
    public Response deleteCohortSamples(
            @PathVariable("sourceKey") String sourceKey,
            @PathVariable("cohortDefinitionId") int cohortDefinitionId
    ) {
        checkUpdatePermissions(cohortDefinitionId, sourceKey);
        SourceEntity source = getSource(sourceKey);
        samplingService.launchDeleteSamplesTasklet(cohortDefinitionId, source.getId());
        return Response.status(Response.Status.ACCEPTED).build();
    }

    private SourceEntity getSource(String sourceKey) {
        SourceEntity source = sourceRepository.findBySourceKey(sourceKey);
        if (source == null) {
            throw new NotFoundException("Source " + sourceKey + " does not exist");
        }
        return source;
    }

    private void checkPermissions(int cohortDefinitionId, String sourceKey) {
        checkReadCohortDefinition(cohortDefinitionId);
        checkReadDataSource(sourceKey);
    }

    private void checkUpdatePermissions(int cohortDefinitionId, String sourceKey) {
        checkUpdateCohortDefinition(cohortDefinitionId);
        checkReadDataSource(sourceKey);
    }

    private void checkReadCohortDefinition(int cohortDefinitionId) {
        var cohortDefinition = cohortDefinitionRepository.findById(cohortDefinitionId);
        if (!cohortDefinition.isPresent()) {
            throw new NotFoundException("Cohort definition " + cohortDefinitionId + " does not exist.");
        }
        if (!authorizationManager.currentUserCanRead(cohortDefinition.get())) {
            throw new AccessDeniedException("You do not have permission to access the cohort definition");
        }
    }

    private void checkUpdateCohortDefinition(int cohortDefinitionId) {
        var cohortDefinition = cohortDefinitionRepository.findById(cohortDefinitionId);
        if (!cohortDefinition.isPresent()) {
            throw new NotFoundException("Cohort definition " + cohortDefinitionId + " does not exist.");
        }
        if (!authorizationManager.currentUserCanUpdate(cohortDefinition.get())) {
            throw new AccessDeniedException(
                    "You do not have permission to update the cohort definition");
        }
    }

    private void checkReadDataSource(String sourceKey) {
        if (!authorizationManager.currentUserCanRead(sourceKey)) {
            throw new AccessDeniedException("You do not have permission to access the data source");
        }
    }

}
